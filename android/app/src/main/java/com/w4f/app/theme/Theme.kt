// Matches the web dashboard's rounded-xl/rounded-md/rounded-full
// vocabulary (`components/Card.tsx`, `components/Button.tsx`) — a softer,
// more rounded corner scale than M3's own defaults, so cards and buttons
// read the same way across both clients.
private val W4FShapes =
  Shapes(
    extraSmall = RoundedCornerShape(6.dp),
    small = RoundedCornerShape(10.dp),
    medium = RoundedCornerShape(14.dp),
    large = RoundedCornerShape(20.dp),
    extraLarge = RoundedCornerShape(28.dp),
  )

@Composable
fun W4FTheme(
  darkTheme: Boolean = isSystemInDarkTheme(),
  // Was `true`: on Android 12+ this made Material You derive every role
  // color from the device's wallpaper, so two phones running the exact
  // same build could render entirely different colors, neither of them
  // W4F's own sky/cyan brand. This is a branded government tool, not a
  // generic utility — its color identity shouldn't depend on the user's
  // wallpaper. Dynamic color stays available as an explicit opt-in
  // (`dynamicColor = true`) for a future "use device colors" setting,
  // but is no longer the default.
  dynamicColor: Boolean = false,
  content: @Composable () -> Unit,
) {
  val colorScheme =
    when {
      dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
        val context = LocalContext.current
        if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
      }
      darkTheme -> DarkColorScheme
      else -> LightColorScheme
    }

  MaterialTheme(colorScheme = colorScheme, typography = Typography, shapes = W4FShapes, content = content)
}
